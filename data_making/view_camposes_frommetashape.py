def create_arrow_from_vector(origin, direction, length=0.5, color=[0, 1, 0]):
    """
    Create an arrow geometry in Open3D from origin, pointing along 'direction'.
    """
    direction = np.asarray(direction, dtype=float)
    direction_norm = np.linalg.norm(direction)
    if direction_norm < 1e-8:
        raise ValueError("Direction vector is too small")
    direction = direction / direction_norm

    # Arrow in its local frame: +Z is its axis
    arrow = o3d.geometry.TriangleMesh.create_arrow(
        cylinder_radius=0.01,
        cone_radius=0.02,
        cylinder_height=length * 0.8,
        cone_height=length * 0.2
    )
    arrow.paint_uniform_color(color)

    # Compute rotation that takes [0, 0, 1] to 'direction'
    z = np.array([0.0, 0.0, 1.0])
    v = np.cross(z, direction)
    c = np.dot(z, direction)

    if np.allclose(direction, z):
        R = np.eye(3)
    elif np.allclose(direction, -z):
        # 180-degree rotation around any axis orthogonal to z
        R = np.array([[1, 0, 0],
                      [0, -1, 0],
                      [0, 0, -1]])
    else:
        s = np.linalg.norm(v)
        vx = np.array([
            [0,     -v[2],  v[1]],
            [v[2],   0,    -v[0]],
            [-v[1],  v[0],  0   ]
        ])
        R = np.eye(3) + vx + vx @ vx * ((1 - c) / (s ** 2))

    # 4x4 transform
    T = np.eye(4)
    T[:3, :3] = R
    T[:3, 3] = origin

    arrow.transform(T)
    return arrow
