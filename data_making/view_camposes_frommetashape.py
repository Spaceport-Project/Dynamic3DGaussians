def visualize_cameras_matplotlib(cameras, frustum_size=0.2, ref_point=None):
    """Visualize cameras with text labels using matplotlib."""
    
    fig = plt.figure(figsize=(15, 12))
    ax = fig.add_subplot(111, projection='3d')
    
    colors = ['r', 'g', 'b', 'y', 'm', 'c']
    
    # Plot reference point
    if ref_point is not None:
        ax.scatter(*ref_point, c='red', s=200, marker='o', label='Reference')
    
    # Plot each camera
    for idx, (cid, data) in enumerate(sorted(cameras.items(), key=lambda x: int(x[0]))):
        pose = data["pose"]
        label = data["label"]
        c = colors[idx % len(colors)]
        
        # Camera position
        cam_pos = pose[:3, 3]
        
        # Camera viewing direction (Z-axis)
        view_dir = pose[:3, 2]
        
        # Plot camera position
        ax.scatter(*cam_pos, c=c, s=50, marker='o')
        
        # Plot viewing direction as arrow
        arrow_length = frustum_size * 2
        ax.quiver(cam_pos[0], cam_pos[1], cam_pos[2],
                 view_dir[0], view_dir[1], view_dir[2],
                 length=arrow_length, color=c, arrow_length_ratio=0.3)
        
        # Add text label
        ax.text(cam_pos[0], cam_pos[1], cam_pos[2], 
               f'  {label}', fontsize=8, color=c, weight='bold')
        
        # Draw frustum edges
        z = 2 * frustum_size
        x = frustum_size
        y = frustum_size
        
        frustum_points = np.array([
            [0, 0, 0],
            [-x, -y, z],
            [x, -y, z],
            [x, y, z],
            [-x, y, z],
        ])
        
        pts_h = np.hstack([frustum_points, np.ones((frustum_points.shape[0], 1))])
        pts_world = (pose @ pts_h.T).T[:, :3]
        
        # Draw frustum lines
        for i in range(1, 5):
            ax.plot([pts_world[0, 0], pts_world[i, 0]],
                   [pts_world[0, 1], pts_world[i, 1]],
                   [pts_world[0, 2], pts_world[i, 2]], c=c, alpha=0.6, linewidth=0.5)
        
        # Draw rectangle at image plane
        for i in range(1, 5):
            j = i % 4 + 1
            ax.plot([pts_world[i, 0], pts_world[j, 0]],
                   [pts_world[i, 1], pts_world[j, 1]],
                   [pts_world[i, 2], pts_world[j, 2]], c=c, alpha=0.6, linewidth=0.5)
    
    # Set labels and title
    ax.set_xlabel('X')
    ax.set_ylabel('Y')
    ax.set_zlabel('Z')
    ax.set_title('Camera Poses with Labels')
    
    # Equal aspect ratio
    max_range = np.array([
        ax.get_xlim3d()[1] - ax.get_xlim3d()[0],
        ax.get_ylim3d()[1] - ax.get_ylim3d()[0],
        ax.get_zlim3d()[1] - ax.get_zlim3d()[0]
    ]).max() / 2.0
    
    mid_x = (ax.get_xlim3d()[0] + ax.get_xlim3d()[1]) * 0.5
    mid_y = (ax.get_ylim3d()[0] + ax.get_ylim3d()[1]) * 0.5
    mid_z = (ax.get_zlim3d()[0] + ax.get_zlim3d()[1]) * 0.5
    
    ax.set_xlim3d([mid_x - max_range, mid_x + max_range])
    ax.set_ylim3d([mid_y - max_range, mid_y + max_range])
    ax.set_zlim3d([mid_z - max_range, mid_z + max_range])
    
    plt.tight_layout()
    plt.show()

